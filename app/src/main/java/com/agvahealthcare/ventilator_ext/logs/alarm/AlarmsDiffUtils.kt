package com.agvahealthcare.ventilator_ext.logs.alarm

import androidx.annotation.Nullable
import androidx.recyclerview.widget.DiffUtil
import com.agvahealthcare.ventilator_ext.database.entities.AlarmDBModel

class AlarmsDiffUtils(var oldList :List<AlarmDBModel>, var newList: List<AlarmDBModel>) : DiffUtil.Callback() {

    override fun getOldListSize(): Int {
        return oldList.size
    }

    override fun getNewListSize(): Int {
        return newList.size
    }

    override fun areItemsTheSame(oldItemPosition: Int, newItemPosition: Int): Boolean {
        return oldList[oldItemPosition].id == newList[newItemPosition].id
    }

    override fun areContentsTheSame(oldItemPosition: Int, newItemPosition: Int): Boolean {
        return oldList[oldItemPosition].id == newList[newItemPosition].id
    }

    @Nullable
    override fun getChangePayload(oldItemPosition: Int, newItemPosition: Int): Any? {
        // Implement method if you're going to use ItemAnimator
        return super.getChangePayload(oldItemPosition, newItemPosition)
    }
}